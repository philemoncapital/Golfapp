/** Generates supabase/migrations/0005_approach_drills.sql from src/data/approach.ts. Run: npm run gen:approach-sql */
import { writeFileSync } from 'node:fs';
import { APPROACH_DRILLS } from '../src/data/approach';

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const rows = APPROACH_DRILLS.map((d) => `(${[q(d.id), 'null', q(d.source), q(d.area), q(d.category), q(d.title), q(d.seen_with), d.duration_min, d.difficulty, q(d.shot_type), j({ de: d.equipment_de }), j(d.text), j(d.scoring), j(d.sources ?? []), 'null'].join(', ')})`);
const src = APPROACH_DRILLS.flatMap((d) => (d.sources ?? []).map((s) => `(${[q(s.title), q(s.author), q(s.url), "'2026-11-07'", q(`Drill ${d.id}; verified 2026-11-07 (docs/PHASE5_PROPOSAL.md 0a); published ${s.date}`)].join(', ')})`));
writeFileSync(new URL('../supabase/migrations/0005_approach_drills.sql', import.meta.url), `-- Golf Pulse – 0005: approach drills approved by David on 2026-11-07 (Phase 5: A1, A2, A3, A5).
-- Generated by scripts/gen-approach-sql.ts from src/data/approach.ts. Run once in the Supabase SQL editor AFTER 0004.
-- Procedures follow the cited sources; scoring zones and HCP tables are our documented assumption (ASSUMPTIONS.md).

insert into public.drills (id, owner_id, source, area, category, title, seen_with, duration_min, difficulty, shot_type, equipment, text, scoring, sources, needs_verification) values
${rows.join(',\n')}
on conflict (id) do update set area = excluded.area, category = excluded.category, title = excluded.title, seen_with = excluded.seen_with,
  duration_min = excluded.duration_min, difficulty = excluded.difficulty, shot_type = excluded.shot_type, equipment = excluded.equipment,
  text = excluded.text, scoring = excluded.scoring, sources = excluded.sources, needs_verification = excluded.needs_verification;

insert into public.sources (title, author, url, accessed_at, note)
select v.title, v.author, v.url, v.accessed_at::date, v.note from (values
${src.join(',\n')}
) v(title, author, url, accessed_at, note)
where not exists (select 1 from public.sources s where s.url = v.url);

-- Existing users: Collector progress now counts the new drills.
do $$ declare u uuid; begin
  for u in select id from public.profiles loop perform public.refresh_achievements_safe(u); end loop;
end $$;
`);
console.log(`0005: ${rows.length} drills, ${src.length} sources`);
