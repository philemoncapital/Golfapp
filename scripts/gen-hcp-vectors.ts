/**
 * Generates supabase/tests/local/hcp_vectors.sql: inputs for every drill plus the HCP the TypeScript engine computes.
 * supabase/tests/hcp_parity_test.sql then checks that the SQL engine (0002) returns exactly the same values.
 * Run: npm run gen:hcp-vectors
 */
import { writeFileSync } from 'node:fs';
import seed from '../src/data/drills.seed.json';
import { resultHcp } from '../src/engine/handicap';
import type { Drill, ResultInput, RadiusBall } from '../src/engine/types';

const drills = seed as unknown as Drill[];
let s = 42; const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
const rows: [string, ResultInput, number][] = [];
const BUCKETS: RadiusBall[] = [0, 1.4, 1.9, 2.9, 3.9, 4.9, 5.9, 6.9].map((d) => ({ dist_m: d, on_green: true }))
  .concat([{ dist_m: 8, on_green: true }, { dist_m: null, on_green: false }]);

for (const d of drills) {
  const sc = d.scoring;
  const add = (input: ResultInput) => rows.push([d.id, input, resultHcp(d, input)]);
  if (sc.type === 'radius_by_band') {
    const n = sc.balls ?? 20;
    for (let k = 0; k < 120; k++) {
      const len = k < 100 ? n : 1 + Math.floor(rnd() * n);
      const bias = rnd();
      add({ kind: 'radius', balls: Array.from({ length: len }, () => BUCKETS[Math.min(9, Math.floor(rnd() * 10 * (0.3 + bias)))]) });
    }
  } else if (sc.type === 'series_triplet') {
    for (let a = 0; a <= 12; a++) for (let b = 0; b <= 6; b++) for (let c = 0; c <= 3; c++) add({ kind: 'triplet', achieved: [a, b, c] });
  } else {
    const ts = sc.bands.map((b) => b.target as number);
    for (let v = Math.min(...ts) - 6; v <= Math.max(...ts) + 6; v += 0.5) add({ kind: 'value', value: v });
    if (sc.type === 'time_lower_better') for (let h = 0; h < 8; h++) add({ kind: 'time_fallback', hits: h, limit_min: 999, required_hits: 8 });
  }
}
const esc = (x: string) => x.replace(/'/g, "''");
const sql = [
  '-- Generated by scripts/gen-hcp-vectors.ts from the TypeScript engine – do not edit by hand.',
  'create schema if not exists pulse_test;',
  'drop table if exists pulse_test.hcp_vectors;',
  'create table pulse_test.hcp_vectors (drill_id text, input jsonb, expected float8);',
  'insert into pulse_test.hcp_vectors values',
  rows.map(([id, input, h]) => `('${esc(id)}', '${esc(JSON.stringify(input))}', ${h})`).join(',\n') + ';',
].join('\n');
writeFileSync(new URL('../supabase/tests/local/hcp_vectors.sql', import.meta.url), sql + '\n');
console.log(`${rows.length} vectors written`);
