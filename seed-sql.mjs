// Generates supabase/seed.sql (booklet drills) from src/data/drills.seed.json.
import { readFileSync, writeFileSync } from 'node:fs';
const drills = JSON.parse(readFileSync('src/data/drills.seed.json', 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const rows = drills.map((d) => `(${[q(d.id), 'null', q(d.source), q(d.area), q(d.category), q(d.title), q(d.seen_with), d.duration_min, d.difficulty, q(d.shot_type), j({ de: d.equipment_de }), j(d.text), j(d.scoring), q(d.needs_verification)].join(', ')})`);
writeFileSync('supabase/seed.sql', `-- Generated by scripts/seed-sql.mjs – do not edit by hand.
insert into public.drills (id, owner_id, source, area, category, title, seen_with, duration_min, difficulty, shot_type, equipment, text, scoring, needs_verification) values
${rows.join(',\n')}
on conflict (id) do update set area = excluded.area, category = excluded.category, title = excluded.title, seen_with = excluded.seen_with,
  duration_min = excluded.duration_min, difficulty = excluded.difficulty, shot_type = excluded.shot_type, equipment = excluded.equipment,
  text = excluded.text, scoring = excluded.scoring, needs_verification = excluded.needs_verification;
`);
console.log(`seed.sql: ${rows.length} drills`);
